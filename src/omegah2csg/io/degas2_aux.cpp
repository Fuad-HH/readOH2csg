#include "omegah2csg/io/degas2_aux.hpp"
#include "omegah2csg/io/atomic_file.hpp"

#include <cstdio>
#include <memory>
#include <stdexcept>

namespace omegah2csg {

namespace {
/// Writes `path` atomically through a printf-style callback.
template <class F>
void write_text(const std::string &path, bool force, F body) {
  AtomicOutput out(path, force);
  {
    std::unique_ptr<std::FILE, int (*)(std::FILE *)> f(
        std::fopen(out.tmp().c_str(), "w"), &std::fclose);
    if (!f)
      throw std::runtime_error("cannot write " + out.tmp());
    body(f.get());
  }
  out.commit();
}

/// `n` values, 10 per line (DEGAS2 sourcefile layout).
template <class F> void columns(std::FILE *f, int n, F item) {
  for (int i = 0; i < n; ++i) {
    item(i);
    if ((i + 1) % 10 == 0 && i != n - 1)
      std::fputs("\n", f);
  }
}
} // namespace

void write_degas2_aux(const std::string &dir, HostSpan<double> xy, int nplasma,
                      int nwall_points, bool force) {
  const std::string base = dir.empty() ? "" : dir + "/";
  write_text(base + "wallfile.txt", force, [&](std::FILE *f) {
    std::fprintf(f, "# Wallfile automatically generated by script\n1 \n#\n");
    std::fprintf(f, "%d\n#\n", static_cast<int>(xy.size / 2));
    for (std::size_t i = 0; i < xy.size / 2; ++i)
      std::fprintf(f, "%26.20f   %26.20f \n", xy[2 * i], xy[2 * i + 1]);
  });
  write_text(base + "plasmafile.txt", force, [&](std::FILE *f) {
    std::fprintf(f, "%10s %10s %10s %10s %10s\n", "zone", "T(1)", "N(1)",
                 "T(2)", "N(2)");
    for (int i = 0; i < nplasma; ++i)
      std::fprintf(f, "%i %e %e %e %e\n", i + 1, 100.0, 1e19, 100.0, 1e19);
  });
  write_text(base + "sourcefile.txt", force, [&](std::FILE *f) {
    std::fputs("#\nstratum\n#\n", f);
    columns(f, nwall_points,
            [&](int i) { std::fprintf(f, "%d ", nplasma + 1 + i); });
    std::fputs("\n#\nsegment\n#\n", f);
    columns(f, nwall_points, [&](int) { std::fputs("0 ", f); });
    std::fputs("\n#\nF\n#\n", f);
    columns(f, nwall_points, [&](int) { std::fprintf(f, "%e ", 1e20); });
  });
}

} // namespace omegah2csg
