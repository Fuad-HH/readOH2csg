# first one is on positive side
def sort_edge_to_face_map(edge_to_face_map, face2edge_map) -> np.ndarray:
    nedges = edge_to_face_map.shape[0]

    for i in range(0, nedges):
        first_face = edge_to_face_map[i, 0]
        for j in range(0, 3):
            edge = face2edge_map[first_face, 2 * j]
            if edge == i:
                first_face_sign = face2edge_map[first_face, 2 * j + 1]
                if first_face_sign == -1:  # then swap
                    edge_to_face_map[i, 0], edge_to_face_map[i, 1] = (
                        edge_to_face_map[i, 1],
                        edge_to_face_map[i, 0],
                    )
                    continue
                if first_face_sign == 1:
                    continue
                else:
                    raise RuntimeError(f"Sign cannon be {first_face_sign}")

    return edge_to_face_map


def write_nodes_to_file(node_coords, wallfile_name="wallfile.txt"):
    num_nodes = int(node_coords.shape[0] / 2)
    wallfile = open(wallfile_name, "w")
    wallfile.write("# Wallfile automatically generated by script\n")
    wallfile.write("1 \n")
    wallfile.write("#\n")
    wallfile.write("%d\n" % num_nodes)
    wallfile.write("#\n")
    for i in range(0, num_nodes):
        wallfile.write(
            "%26.20f   %26.20f \n" % (node_coords[2 * i], node_coords[2 * i + 1])
        )
    wallfile.close()


def write_dummy_bg_files_aux(nzone, nwall_input, stratum_start):
    nwallsegs = nwall_input
    nperline = 10

    f = open("plasmafile.txt", "w")
    f.write("%10s %10s %10s %10s %10s\n" % ("zone", "T(1)", "N(1)", "T(2)", "N(2)"))
    for i in range(0, nzone):
        f.write("%i %e %e %e %e\n" % (i + 1, 100.0, 1e19, 100.0, 1e19))
    f.close()

    f = open("sourcefile.txt", "w")
    f.write("#\nstratum\n#\n")
    for i in range(0, nwallsegs):
        f.write("%d " % (stratum_start + i))
        if ((i + 1) % nperline == 0) and i != nwallsegs - 1:
            f.write("\n")
    f.write("\n")
    f.write("#\nsegment\n#\n")
    for i in range(0, nwallsegs):
        f.write("%d " % (0))
        if ((i + 1) % nperline == 0) and i != nwallsegs - 1:
            f.write("\n")
    f.write("\n")
    f.write("#\nF\n#\n")
    for i in range(0, nwallsegs):
        f.write("%e " % (1e20))
        if ((i + 1) % nperline == 0) and i != nwallsegs - 1:
            f.write("\n")


