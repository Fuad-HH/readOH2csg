    boundaries_var[:] = boundaries

    # ------------------------ Surfaces ------------------------------------ #
    surfaces = np.zeros([Nedge, 2, 2], dtype=int)
    # pointers uses 0 based indexing
    surfaces[:Nedge, 0, 0] = 1 + 2 * np.arange(Nedge)
    surfaces[:Nedge, 0, 1] = 0 + 2 * np.arange(Nedge)
    # number of faces
    for i in range(0, Nedge):
        pos_face = edge_to_face_map_sorted[i, 0]
        neg_face = edge_to_face_map_sorted[i, 1]
        if neg_face == -1 and pos_face != -1:
            surfaces[i, 1, 0] = 0
            surfaces[i, 1, 1] = 1
        elif pos_face == -1 and neg_face != -1:
            surfaces[i, 1, 1] = 0
            surfaces[i, 1, 0] = 1
        elif neg_face != -1 and pos_face != -1:
            surfaces[i, 1, :] = 1
        else:
            raise RuntimeError(
                f"pos_face={pos_face}, neg_face={neg_face} is not correct!"
            )

    surfaces_var[:] = surfaces

    # ----------------------- Neighbors (Edge Adjacency Info) ----------------- #
    neighbors = np.zeros(nneighbors + 1, dtype=int)
    edge_to_face_map_sorted[~(edge_to_face_map_sorted == -1)] += (
        1  # use one based indexing
    )
    neighbors[0 : Nedge * 2] = edge_to_face_map_sorted.reshape(Nedge * 2)
    neighbors_var[:] = neighbors

    # --------------------- Surface Coefficients ------------------------------ #
    # TODO Create a better documentation of the coeffs
    surface_coeffs = np.zeros([Nedge, 11])
    # -b ^ 2 for a cone, -R ^ 2 for a cylinder, -Z0 for a plane
    surface_coeffs[:Nedge, 0] = edge_coefficients[:, 3]
    # b = 0 for a cylinder, 1/2 for a plane, and intercept for a cone
    surface_coeffs[:Nedge, 3] = edge_coefficients[:, 2]
    # m=1 for cylinder, slope for a cone, and 0 for a plane
    surface_coeffs[:Nedge, 4] = edge_coefficients[:, 0]
    surface_coeffs[:Nedge, 5] = edge_coefficients[:, 0]
    # in notebook np.where(np.logical_or(planecond,cylcond),np.zeros(Nsurfs),-np.ones(Nsurfs))
    surface_coeffs[:Nedge, 6] = edge_coefficients[:, 1]
    # cone up or down direction flag
    surface_coeffs[:Nedge, 10] = edge_coefficients[:, 4]

    surface_coeffs_var[:] = surface_coeffs

    # --------------------- Zones ------------------------------------------ #
    zone_center = np.zeros([num_zones + 1, 3])
    zone_center[0:Nplasma, 0] = centroids[0:Nplasma, 0]
    zone_center[0:Nplasma, 2] = centroids[0:Nplasma, 1]
    # they do specify it with the first cells centroid we are doing it with the last
    # for this zone
    assert cells[-1, 3] == num_zones + 1, (
        f"The next 2 lines won't work if this assertion fails. {cells[-1,3]=}, {num_zones=}"
    )
    zone_center[-1, 0] = centroids[-1, 0]
    zone_center[-1, 2] = centroids[-1, 1]
